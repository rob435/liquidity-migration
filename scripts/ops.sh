#!/usr/bin/env bash
# One thin operator-facing router for the surviving demo and research operations.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SSH_TARGET="${SSH_TARGET:-root@116.202.15.128}"
REPO_DIR="${REPO_DIR:-/opt/liquidity-migration}"

if [[ -n "${PYTHON:-}" ]]; then
  PYTHON_BIN="$PYTHON"
elif [[ -x "$ROOT_DIR/.venv/bin/python" ]]; then
  PYTHON_BIN="$ROOT_DIR/.venv/bin/python"
elif [[ -x "$ROOT_DIR/.venv/Scripts/python.exe" ]]; then
  PYTHON_BIN="$ROOT_DIR/.venv/Scripts/python.exe"
else
  PYTHON_BIN="python3"
fi

# The canonical VPS scripts consume these environment variables.
export SSH_TARGET REPO_DIR

usage() {
  cat <<'EOF'
Usage: scripts/ops.sh <command> [arguments]

Operator commands:
  status [ARGS...]             read-only VPS verification
  units                        list the fleet's units and timers
  logs UNIT [LINES]            one unit's journal (default 100 lines)
  restart UNIT...              restart units
  stop UNIT...                 stop units
  start UNIT...                start units
  equity [ARGS...]             standard descriptive equity curves
  research-refresh [ARGS...]   append-first data/features/backtest workflow
  reset [ARGS...]              remote ledger-reset preview (dry-run by default)
  venue-accounting [ARGS...]   reconcile demo accounting on the host; LOCAL=1
                               runs it against this checkout instead
  wedged-command [--environment demo|mainnet] [ARGS...]
                               report/probe/resolve wedged order commands
                               (default demo; the reconciler already does this
                               automatically in both realms)
  real-money preflight         report every remaining arming step (read-only)
  real-money render-profile [--execute --output PATH]
                               render the operational profile from the
                               RM_* dials in the owner's env file
  real-money create-state-roots [--execute]
                               create the mainnet state roots; dry run without
                               --execute
  deploy MODE [ARGS...]        MODE is install|activate|staged|rollout|
                               stop-mainnet
  help                         show this help and do nothing else

A UNIT that does not already start with `liquidity-migration-` gets the prefix:
`logs bybit-carry-demo.service` reads
`liquidity-migration-bybit-carry-demo.service`.

Environment overrides:
  SSH_TARGET   VPS SSH destination (default: root@116.202.15.128)
  REPO_DIR     repository path on the VPS (default: /opt/liquidity-migration)
  PYTHON       Python executable/path for local tools and tests

Mutating verbs run against the live host; see docs/operations.md.
EOF
}

die_usage() {
  echo "ERROR: $*" >&2
  echo >&2
  usage >&2
  exit 2
}

# One remote entry point. Values are serialized as Bash literals and
# reconstructed as a remote array, which preserves argument boundaries
# (including spaces and metacharacters) without eval: the only parsed source is
# generated by Bash's own printf %q.
remote_exec() {
  local script="$1"
  shift
  local -a remote_args=("$@")
  local arg
  {
    printf 'REPO_DIR=%q\n' "$REPO_DIR"
    printf 'REMOTE_ARGS=('
    for arg in ${remote_args[@]+"${remote_args[@]}"}; do
      printf ' %q' "$arg"
    done
    printf ' )\n'
    printf 'set -euo pipefail\n'
    printf '%s\n' "$script"
  } | ssh -o BatchMode=yes -o ConnectTimeout=10 -- "$SSH_TARGET" bash -s
}

# probe/resolve read venue truth, so the demo-owner credentials are loaded
# exactly as the unit loads them.
REMOTE_CREDENTIAL_PRELUDE='set -a
. /etc/liquidity-migration/bybit-demo.env
. /etc/liquidity-migration/account-execution.env
set +a'

qualify_unit() {
  case "$1" in
    liquidity-migration-*) printf '%s' "$1" ;;
    *) printf 'liquidity-migration-%s' "$1" ;;
  esac
}

qualified_units() {
  local unit
  QUALIFIED_UNITS=()
  for unit in "$@"; do
    QUALIFIED_UNITS+=("$(qualify_unit "$unit")")
  done
}

remote_reset() {
  local -a reset_args=("$@")
  local arg has_execute=0 has_dry_run=0
  for arg in ${reset_args[@]+"${reset_args[@]}"}; do
    if [[ "$arg" == "--execute" ]]; then
      has_execute=1
    elif [[ "$arg" == "--dry-run" ]]; then
      has_dry_run=1
    fi
  done

  # Make the safe default explicit at the remote boundary. The canonical reset
  # script independently defaults to dry-run and requires --execute as well.
  if (( has_execute == 0 && has_dry_run == 0 )); then
    reset_args=(--dry-run ${reset_args[@]+"${reset_args[@]}"})
  fi

  remote_exec 'cd "$REPO_DIR"
exec bash scripts/maintain/reset_demo_ledgers.sh "${REMOTE_ARGS[@]}"' \
    ${reset_args[@]+"${reset_args[@]}"}
}

remote_python_module() {
  local module="$1"
  shift
  remote_exec 'cd "$REPO_DIR"
exec .venv/bin/python -m "${REMOTE_ARGS[@]}"' "$module" "$@"
}

command="${1:-help}"
if [[ "$#" -gt 0 ]]; then
  shift
fi

case "$command" in
  help|-h|--help)
    usage
    ;;
  status)
    exec "$ROOT_DIR/scripts/deploy_vps_live.sh" verify "$@"
    ;;
  units)
    remote_exec "systemctl list-units 'liquidity-migration-*' --all --no-legend --no-pager --plain
systemctl list-timers 'liquidity-migration-*' --no-pager"
    ;;
  logs)
    [[ "$#" -ge 1 ]] || die_usage "logs requires a unit name"
    remote_exec 'exec journalctl -u "${REMOTE_ARGS[0]}" -n "${REMOTE_ARGS[1]}" --no-pager -o short-iso' \
      "$(qualify_unit "$1")" "${2:-100}"
    ;;
  restart|stop|start)
    [[ "$#" -ge 1 ]] || die_usage "$command requires at least one unit name"
    qualified_units "$@"
    remote_exec "exec systemctl $command \"\${REMOTE_ARGS[@]}\"" "${QUALIFIED_UNITS[@]}"
    ;;
  equity)
    exec bash "$ROOT_DIR/scripts/research/equity_curves.sh" "$@"
    ;;
  research-refresh)
    exec bash "$ROOT_DIR/scripts/research/research_refresh.sh" "$@"
    ;;
  reset)
    remote_reset "$@"
    ;;
  venue-accounting)
    # The evidence and the credentials live on the host, so this runs there.
    # LOCAL=1 runs it against this checkout instead.
    if [[ "${LOCAL:-0}" == "1" ]]; then
      exec "$PYTHON_BIN" "$ROOT_DIR/scripts/maintain/reconcile_bybit_demo_accounting.py" "$@"
    fi
    remote_exec 'cd "$REPO_DIR"
'"$REMOTE_CREDENTIAL_PRELUDE"'
exec .venv/bin/python scripts/maintain/reconcile_bybit_demo_accounting.py \
  --account-root data/bybit-account-execution \
  "${REMOTE_ARGS[@]}"' "$@"
    ;;
  real-money)
    # The owner-facing arming surface. `preflight` reads only and never prints
    # a secret. `render-profile` without --execute prints the profile to
    # stdout; with --execute it writes exactly one non-secret artifact and
    # refuses any dial set that does not pass the load-time envelope proof.
    # `create-state-roots` without --execute lists the directories it would
    # create; with --execute it creates them. None of them sets REAL_MONEY,
    # writes a credential, or starts a unit -- every one of those is the
    # owner's own act.
    # No argument means preflight, and it has to be *passed*: leaving argv
    # empty ran the module with no subcommand and got an argparse usage error
    # instead of the read-only report the operator asked for.
    if [[ "$#" -eq 0 ]]; then
      set -- preflight
    fi
    case "${1:-}" in
      preflight|render-profile|create-state-roots) ;;
      *) die_usage "real-money subcommand must be preflight, render-profile, or create-state-roots" ;;
    esac
    # LOCAL=1 runs it against this checkout instead of the VPS, so the dials
    # can be proved before anything is copied to the host.
    if [[ "${LOCAL:-0}" == "1" ]]; then
      exec "$PYTHON_BIN" -m liquidity_migration.policy.real_money_arming "$@"
    fi
    remote_python_module liquidity_migration.policy.real_money_arming "$@"
    ;;
  flatten)
    # Retired with the Python account owner. Flatten worked by publishing zero
    # targets into the owner's intent inbox; the engine reads target book files
    # and never had an inbox, so there is nothing left to drain them. Closing a
    # book is a manual job at the venue until the engine grows its own path.
    echo "ops.sh flatten: retired with the Python account owner." >&2
    echo "Close positions at the venue by hand, or stop the sleeve and let exits run." >&2
    exit 2
    ;;
  wedged-command)
    # `report` and `probe` read only. `resolve` writes one journal transition
    # and never resends an order; it refuses outright when the venue still
    # holds the order or cannot be read. The reconciler now does this by itself
    # in both realms, so this stays for inspection and for a wedge the evidence
    # ladder deliberately refuses.
    wedged_environment=demo
    if [[ "${1:-}" == "--environment" ]]; then
      wedged_environment="${2:-}"
      shift 2 || die_usage "--environment needs demo or mainnet"
    fi
    case "$wedged_environment" in
      demo)
        wedged_prelude="$REMOTE_CREDENTIAL_PRELUDE"
        wedged_root=data/bybit-account-execution
        wedged_account=bybit-demo-unified
        ;;
      mainnet)
        wedged_prelude='set -a
. /etc/liquidity-migration/bybit-mainnet.env
. /etc/liquidity-migration/account-execution-mainnet.env
set +a'
        wedged_root=/var/lib/liquidity-migration/account-mainnet
        wedged_account=bybit-mainnet-unified
        ;;
      *) die_usage "wedged-command --environment must be demo or mainnet" ;;
    esac
    remote_exec 'cd "$REPO_DIR"
'"$wedged_prelude"'
exec .venv/bin/python -m liquidity_migration.venue.wedged_command_resolution \
  --account-root '"$wedged_root"' \
  --account-id '"$wedged_account"' \
  --realm '"$wedged_environment"' \
  "${REMOTE_ARGS[@]}"' "$@"
    ;;
  deploy)
    # A leading --execute is accepted and discarded: it used to be mandatory.
    if [[ "${1:-}" == "--execute" ]]; then
      shift
    fi
    case "${1:-}" in
      install|activate|staged|rollout|stop-mainnet) ;;
      *) die_usage "deploy mode must be install, activate, staged, rollout, or stop-mainnet" ;;
    esac
    exec "$ROOT_DIR/scripts/deploy_vps_live.sh" "$@"
    ;;
  *)
    die_usage "unknown command '$command'"
    ;;
esac
